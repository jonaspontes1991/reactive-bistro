CREATE TABLE IF NOT EXISTS users
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    username VARCHAR(50)  NOT NULL UNIQUE,
    email    VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(20)  NOT NULL CHECK (role IN ('CLIENT', 'WAITER', 'CHEF', 'MANAGER', 'ADMIN'))
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

CREATE TABLE IF NOT EXISTS tables
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number BIGINT      NOT NULL UNIQUE,
    status       VARCHAR(20) NOT NULL CHECK (status IN ('RESERVED', 'OCCUPIED', 'AVAILABLE')),
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS menu_items
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100)     NOT NULL,
    description TEXT             NOT NULL,
    price       DOUBLE PRECISION NOT NULL CHECK (price >= 0),
    category    VARCHAR(50)      NOT NULL
);

CREATE TABLE IF NOT EXISTS orders
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number BIGINT      NOT NULL REFERENCES tables (table_number),
    waiter_id    BIGINT      NOT NULL REFERENCES users (id),
    client_id    BIGINT      NOT NULL REFERENCES users (id),
    status       VARCHAR(20) NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_orders_table_number ON orders (table_number);
CREATE INDEX IF NOT EXISTS idx_orders_waiter_id ON orders (waiter_id);
CREATE INDEX IF NOT EXISTS idx_orders_client_id ON orders (client_id);
